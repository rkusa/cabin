//! Snapshots the CSS of every style method that takes no or a single simple argument, each on its
//! own and all of them chained (in order and in reverse), to catch unintended changes in the
//! generated CSS when refactoring styles. Class names are normalized, as they are covered by the
//! other style snapshots.
//!
//! The list of methods is generated from the source. If `generated_is_up_to_date` fails, update it
//! with `UPDATE_STYLE_METHODS=1 cargo test --test style_methods`.

use cabin::style::collector::StyleCollector;
use cabin::style::{Style as _, SubStyle as _};

// Not formatted, as `generated_is_up_to_date` compares it with the generated output.
#[rustfmt::skip]
#[path = "style_methods/generated.rs"]
mod generated;

type Method = fn(StyleCollector) -> StyleCollector;

const SOURCES: &[&str] = &["src/style.rs", "src/style/sub_style.rs"];
const GENERATED: &str = "tests/style_methods/generated.rs";

#[test]
fn css_of_all_methods() {
    let mut out = String::new();
    for (name, f) in generated::METHODS {
        out += &format!("== {name}\n");
        out += &normalize_class_names(f(StyleCollector::default()).build());
    }

    let chain = generated::METHODS
        .iter()
        .fold(StyleCollector::default(), |c, (_, f)| f(c));
    out += "== chain\n";
    out += &normalize_class_names(chain.build());

    let reverse = generated::METHODS
        .iter()
        .rev()
        .fold(StyleCollector::default(), |c, (_, f)| f(c));
    out += "== reverse chain\n";
    out += &normalize_class_names(reverse.build());

    insta::assert_snapshot!(out);
}

#[test]
fn generated_is_up_to_date() {
    let root = env!("CARGO_MANIFEST_DIR");
    let mut methods = Vec::new();
    for source in SOURCES {
        let src = std::fs::read_to_string(format!("{root}/{source}")).unwrap();
        for method in style_methods(&src) {
            if !methods.iter().any(|(name, _)| *name == method.0) {
                methods.push(method);
            }
        }
    }

    let mut expected = String::from(
        "// @generated by `UPDATE_STYLE_METHODS=1 cargo test --test style_methods`. Don't \
         edit.\n\nuse super::*;\n\npub const METHODS: &[(&str, Method)] = &[\n",
    );
    for (name, arg) in &methods {
        expected += &format!("    ({name:?}, |c| c.{name}({arg})),\n");
    }
    expected += "];\n";

    let path = format!("{root}/{GENERATED}");
    if std::env::var_os("UPDATE_STYLE_METHODS").is_some() {
        std::fs::write(&path, &expected).unwrap();
        return;
    }
    let actual = std::fs::read_to_string(&path).unwrap_or_default();
    assert!(
        actual == expected,
        "{GENERATED} is outdated, update it with `UPDATE_STYLE_METHODS=1 cargo test --test \
         style_methods`"
    );
}

/// Finds `fn name(self[, arg: Type]) -> Self` methods and returns their name and an argument
/// expression for supported argument types.
fn style_methods(src: &str) -> Vec<(String, &'static str)> {
    let mut methods = Vec::new();
    let mut rest = src;
    while let Some(ix) = rest.find("fn ") {
        rest = &rest[ix + 3..];
        let name: String = rest
            .chars()
            .take_while(|c| c.is_ascii_alphanumeric() || *c == '_')
            .collect();
        let mut sig = &rest[name.len()..];
        if sig.starts_with('<') {
            let Some(len) = closing(sig, '<', '>') else {
                continue;
            };
            sig = &sig[len..];
        }
        if !sig.starts_with('(') {
            continue;
        }
        let Some(len) = closing(sig, '(', ')') else {
            continue;
        };
        let params = &sig[1..len - 1];
        if !sig[len..].trim_start().starts_with("-> Self") {
            continue;
        }
        let params = params.split_whitespace().collect::<Vec<_>>().join(" ");
        let params = params.trim_end_matches(',');
        let Some(arg) = params
            .strip_prefix("mut self")
            .or_else(|| params.strip_prefix("self"))
        else {
            continue;
        };
        // The parameter types without their names, e.g. `u32, u32`.
        let arg = arg.trim_start_matches(',').trim();
        let Some(types) = (!arg.is_empty())
            .then(|| {
                arg.split(',')
                    .map(|p| p.split_once(':').map(|(_, ty)| ty.trim()))
            })
            .map(|types| types.collect::<Option<Vec<_>>>())
            .unwrap_or(Some(Vec::new()))
        else {
            continue;
        };
        let arg = match types.join(", ").as_str() {
            "" => "",
            "impl Into<Length>" => "2",
            "&'static str" => "\"red\"",
            "i16" => "3",
            "f32" => "1.5",
            "u16" => "4",
            "u32" => "5",
            "i32" => "-2",
            "u32, u32" => "16, 9",
            _ => continue,
        };
        methods.push((name, arg));
    }
    methods
}

/// The length of `s` up to and including the bracket closing its first character, ignoring `->`.
fn closing(s: &str, open: char, close: char) -> Option<usize> {
    let mut depth = 0;
    let mut prev = ' ';
    for (ix, c) in s.char_indices() {
        if c == open {
            depth += 1;
        } else if c == close && !(close == '>' && prev == '-') {
            depth -= 1;
            if depth == 0 {
                return Some(ix + 1);
            }
        }
        prev = c;
    }
    None
}

/// Replaces class names (`_` followed by 8 hex digits or `_`) with `_X`.
fn normalize_class_names(css: String) -> String {
    let bytes = css.as_bytes();
    let mut out = String::with_capacity(css.len());
    let mut ix = 0;
    while ix < bytes.len() {
        if bytes[ix] == b'_'
            && ix + 9 <= bytes.len()
            && bytes[ix + 1..ix + 9]
                .iter()
                .all(|c| c.is_ascii_hexdigit() || *c == b'_')
        {
            out += "_X";
            ix += 9;
        } else {
            out.push(bytes[ix] as char);
            ix += 1;
        }
    }
    out
}
